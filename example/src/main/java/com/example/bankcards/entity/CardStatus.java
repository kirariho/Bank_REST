package com.example.bankcards.entity;

/**
 * Перечисление (Enum) для статусов банковской карты.
 * Используется для определения текущего состояния карты.
 */
public enum CardStatus {

    /**
     * Карта активна и может использоваться.
     */
    ACTIVE,

    /**
     * Карта заблокирована и не может использоваться.
     */
    BLOCKED,

    /**
     * Срок действия карты истёк.
     */
    EXPIRED
}
